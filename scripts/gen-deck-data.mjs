// Generates the canonical deck module (src/deck.ts) and the browser copy
// (public/static/deck-data.js) from a single source, so the server prompt and
// the client UI can never drift apart.
//
//   node scripts/gen-deck-data.mjs
//
// Source of truth: public/static/deck-data.js (the 78-card Quantum
// Navigational Tools deck, canonical and final per the design handoff).
import { readFileSync, writeFileSync } from 'node:fs'

const BROWSER_FILE = 'public/static/deck-data.js'
const TS_FILE = 'src/deck.ts'

const raw = readFileSync(BROWSER_FILE, 'utf8')

// Extract the array literal between the first '[' and the final '];'
const start = raw.indexOf('[')
const end = raw.lastIndexOf(']')
if (start === -1 || end === -1) throw new Error('could not locate deck array literal')

const arrayLiteral = raw.slice(start, end + 1)

// Pull the header comment (lines starting with //) for reuse in the TS file
const headerComments = raw
  .split('\n')
  .filter((l) => l.trim().startsWith('//'))
  .map((l) => l.replace(/^/, ''))
  .join('\n')

const ts = `// AUTO-GENERATED by scripts/gen-deck-data.mjs — do not edit by hand.
// Canonical 78-card Quantum Navigational Tools deck. Shared by the Worker
// (prompt context) and the browser (public/static/deck-data.js).
${headerComments}

export type Card = {
  n: number
  num: string
  name: string
  kw: string
  meaning: string
}

export const DECK: Card[] = ${arrayLiteral}

export const DECK_BY_NUMBER: Record<number, Card> = Object.fromEntries(
  DECK.map((c) => [c.n, c]),
)

/** Look up cards by their deck number, skipping any that don't resolve. */
export function cardsByNumber(nums: number[]): Card[] {
  return nums
    .map((n) => DECK_BY_NUMBER[n])
    .filter((c): c is Card => Boolean(c))
}
`

// The literal uses unquoted keys, so count cards by their `{ n:` markers
// rather than JSON.parse-ing it.
const cardCount = (arrayLiteral.match(/\{\s*n:\s*\d+/g) || []).length
if (cardCount !== 78) {
  throw new Error(`expected 78 cards in the deck, found ${cardCount}`)
}

writeFileSync(TS_FILE, ts)
console.log(`wrote ${TS_FILE} (${ts.length} bytes, ${cardCount} cards)`)

// The browser copy keeps the window.QNT_DECK shape the reading script expects.
const browser = `// AUTO-GENERATED by scripts/gen-deck-data.mjs — do not edit by hand.
${headerComments}

window.QNT_DECK = ${arrayLiteral};
`
writeFileSync(BROWSER_FILE, browser)
console.log(`wrote ${BROWSER_FILE} (${browser.length} bytes)`)
